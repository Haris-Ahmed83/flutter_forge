/// Base class for all localized strings.
///
/// In a real generated file, this would be an abstract class.
abstract class AppLocalizations {
  AppLocalizations(String locale) : localeName = Intl.canonicalizedLocale(locale);

  final String localeName;

  // This static field is used internally by the generated code to store the
  // current instance of AppLocalizations for direct access without a BuildContext.
  static AppLocalizations? _current;

  /// Provides direct access to the current AppLocalizations instance.
  ///
  /// Useful for non-widget contexts, but generally `AppLocalizations.of(context)`
  /// is preferred when a BuildContext is available.
  static AppLocalizations get current {
    assert(_current != null,
        'No instance of AppLocalizations present. Did you add AppLocalizations.delegate to your MaterialApp.localizationsDelegates?');
    return _current!;
  }

  /// The delegate for AppLocalizations, responsible for loading the correct locale.
  static const LocalizationsDelegate<AppLocalizations> delegate =
      _AppLocalizationsDelegate();

  /// Returns an instance of AppLocalizations for the given `context`.
  ///
  /// This method is typically used to access localized strings throughout the app.
  static AppLocalizations of(BuildContext context) {
    final AppLocalizations? result = Localizations.of<AppLocalizations>(context, AppLocalizations);
    assert(result != null, 'No instance of AppLocalizations present. Did you add AppLocalizations.delegate to your MaterialApp.localizationsDelegates?');
    return result!;
  }

  // Define abstract getters for each localized string.
  // These correspond to the keys in your ARB files.
  String get appTitle;
  String get welcomeMessage;
  String get changeLanguage;
  String get helloWorld;
  String get aboutApp;

  /// Example of a method with a placeholder.
  String currentLanguage(String languageName);
}

/// Concrete implementation for English (en).
class AppLocalizationsEn extends AppLocalizations {
  AppLocalizationsEn() : super('en');

  @override
  String get appTitle => 'Multi-Language App';
  @override
  String get welcomeMessage => 'Welcome to the multi-language app!';
  @override
  String get changeLanguage => 'Change Language';
  @override
  String get helloWorld => 'Hello, World!';
  @override
  String get aboutApp => 'This is a simple Flutter application demonstrating localization using the intl package. You can switch between different languages to see the content change dynamically.';

  @override
  String currentLanguage(String languageName) {
    return 'Current language: $languageName';
  }
}

