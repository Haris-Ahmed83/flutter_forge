/// The delegate for AppLocalizations.
///
/// This class is responsible for loading the correct AppLocalizations
/// implementation based on the current locale.
class _AppLocalizationsDelegate extends LocalizationsDelegate<AppLocalizations> {
  const _AppLocalizationsDelegate();

  /// Defines which locales are supported by your app.
  @override
  bool isSupported(Locale locale) {
    return ['en', 'es', 'fr'].contains(locale.languageCode);
  }

  /// Loads the appropriate AppLocalizations instance for the given locale.
  @override
  Future<AppLocalizations> load(Locale locale) {
    final String name = Intl.canonicalizedLocale(locale.toString());
    Intl.defaultLocale = name;
    AppLocalizations result;
    if (locale.languageCode == 'es') {
      result = AppLocalizationsEs();
    } else if (locale.languageCode == 'fr') {
      result = AppLocalizationsFr();
    } else {
      // Default to English if locale not explicitly supported or found
      result = AppLocalizationsEn();
    }
    AppLocalizations._current = result; // Set the static current instance
    return Future.value(result);
  }

  /// Indicates whether the delegate should reload its localizations.
  ///
  /// Typically returns `false` unless the list of supported locales changes,
  /// or if you need to force a reload for dynamic content.
  @override
  bool shouldReload(_AppLocalizationsDelegate old) => false;
}

