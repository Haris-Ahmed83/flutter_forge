/// The root widget of the application.
///
/// This is a StatefulWidget to manage the current locale, allowing dynamic
/// language switching without restarting the app.
class MyApp extends StatefulWidget {
  const MyApp({super.key});

  @override
  State<MyApp> createState() => _MyAppState();
}

class _MyAppState extends State<MyApp> {
  // Default locale, can be changed dynamically.
  Locale _locale = const Locale('en');

  /// Callback to update the app's locale.
  ///
  /// When called, it triggers a `setState` to rebuild the `MaterialApp` with
  /// the new locale, effectively changing the app's language.
  void setLocale(Locale newLocale) {
    setState(() {
      _locale = newLocale;
    });
  }

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      // The title displayed in the device's app switcher. This is not localized
      // by `AppLocalizations` directly, but can be set to a static string.
      title: 'Multi-Language App',
      theme: ThemeData(
        colorScheme: ColorScheme.fromSeed(seedColor: Colors.deepPurple),
        useMaterial3: true,
      ),
      // Configure localization delegates and supported locales.
      // These are crucial for `intl` to work correctly.
      localizationsDelegates: const [
        _AppLocalizationsDelegate(), // Our custom delegate for app-specific strings
        GlobalMaterialLocalizations.delegate, // Material widgets localization
        GlobalWidgetsLocalizations.delegate, // Text direction, etc.
        GlobalCupertinoLocalizations.delegate, // iOS style widgets localization
      ],
      supportedLocales: const [
        Locale('en', ''), // English
        Locale('es', ''), // Spanish
        Locale('fr', ''), // French
      ],
      locale: _locale, // Set the current locale from state, enabling dynamic changes.
      home: _MyHomePage(
        title: 'Multi-Language App',
        onLocaleChanged: setLocale, // Pass the callback to MyHomePage for language switching.
      ),
    );
  }
}

