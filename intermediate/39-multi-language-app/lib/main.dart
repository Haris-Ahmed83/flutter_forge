/// The main page of the application, demonstrating localized content.
class _MyHomePage extends StatelessWidget {
  const _MyHomePage({
    required this.title,
    required this.onLocaleChanged,
    super.key,
  });

  final String title;
  final Function(Locale) onLocaleChanged;

  @override
  Widget build(BuildContext context) {
    // Access localized strings using AppLocalizations.of(context).
    // This method ensures the correct locale's strings are retrieved.
    final AppLocalizations localizations = AppLocalizations.of(context);

    // Helper map for displaying language names in the UI.
    // In a more complex app, these names themselves could be localized.
    final Map<String, String> languageNames = {
      'en': 'English',
      'es': 'Español',
      'fr': 'Français',
    };

    // Get the current locale from the context to display its name.
    final String currentLangCode = Localizations.localeOf(context).languageCode;
    final String currentLangName = languageNames[currentLangCode] ?? currentLangCode;

    return Scaffold(
      appBar: AppBar(
        backgroundColor: Theme.of(context).colorScheme.inversePrimary,
        title: Text(localizations.appTitle), // Localized app title
        actions: [
          // Language selection dropdown using PopupMenuButton.
          PopupMenuButton<Locale>(
            onSelected: (Locale selectedLocale) {
              onLocaleChanged(selectedLocale); // Call the callback to update the app's locale.
            },
            icon: const Icon(Icons.language),
            itemBuilder: (BuildContext context) {
              // Generate menu items for each supported locale.
              return AppLocalizations.delegate.supportedLocales.map((Locale locale) {
                return PopupMenuItem<Locale>(
                  value: locale,
                  child: Text(languageNames[locale.languageCode] ?? locale.languageCode),
                );
              }).toList();
            },
          ),
        ],
      ),
      body: SingleChildScrollView(
        padding: const EdgeInsets.all(16.0),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: <Widget>[
            Text(
              localizations.welcomeMessage, // Localized welcome message
              style: Theme.of(context).textTheme.headlineMedium?.copyWith(
                    color: Theme.of(context).colorScheme.primary,
                  ),
            ),
            const SizedBox(height: 24.0),
            Text(
              localizations.currentLanguage(currentLangName), // Localized string with placeholder
              style: Theme.of(context).textTheme.titleLarge,
            ),
            const SizedBox(height: 16.0),
            Divider(color: Theme.of(context).colorScheme.outlineVariant),
            const SizedBox(height: 16.0),
            Text(
              localizations.helloWorld, // Another localized string
              style: Theme.of(context).textTheme.headlineSmall,
            ),
            const SizedBox(height: 16.0),
            Text(
              localizations.aboutApp, // Localized paragraph
              style: Theme.of(context).textTheme.bodyLarge,
              textAlign: TextAlign.justify,
            ),
            const SizedBox(height: 32.0),
            // Example of a button with non-localized text, for comparison.
            ElevatedButton.icon(
              onPressed: () {
                ScaffoldMessenger.of(context).showSnackBar(
                  SnackBar(content: Text('You clicked a button! (Not localized)')),
                );
              },
              icon: const Icon(Icons.info_outline),
              label: const Text('More Info'), // This text is NOT localized.
              style: ElevatedButton.styleFrom(
                padding: const EdgeInsets.symmetric(horizontal: 24, vertical: 12),
                textStyle: Theme.of(context).textTheme.titleMedium,
              ),
            ),
          ],
        ),
      ),
    );
  }
}
